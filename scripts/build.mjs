import { chmod, mkdir, readFile, writeFile } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import { dirname } from "node:path";
import { buildForNodeEngineFloor } from "./node-target.mjs";
import { generatedFiles, serialize } from "./manifests.mjs";
import { bundledNotices } from "./bundled-notices.mjs";

const root = new URL("../", import.meta.url);
const output = new URL("plugin/lib/grokpair.js", root);
const packageJson = JSON.parse(await readFile(new URL("package.json", root), "utf8"));
await mkdir(new URL("plugin/lib/", root), { recursive: true });

const typecheck = spawnSync("pnpm", ["exec", "tsc", "-p", "tsconfig.json"], {
  cwd: root,
  encoding: "utf8"
});
if (typecheck.status !== 0) {
  process.stderr.write(typecheck.stdout);
  process.stderr.write(typecheck.stderr);
  process.exit(typecheck.status ?? 1);
}

const result = await buildForNodeEngineFloor(packageJson.engines?.node, {
  absWorkingDir: root.pathname,
  entryPoints: [new URL("src/agent-main.ts", root).pathname],
  outfile: output.pathname,
  platform: "node",
  format: "esm",
  bundle: true,
  sourcemap: false,
  legalComments: "none",
  metafile: true,
  banner: { js: "#!/usr/bin/env node\n// Generated by esbuild from grokpair and third-party sources, combined and\n// transformed for distribution. Original licenses and attributions:\n// ../LICENSE and ../THIRD_PARTY_NOTICES.md." }
});
const bundled = await readFile(output, "utf8");
await writeFile(output, bundled.replace(/^[\t ]+$/gm, ""));
await chmod(output, 0o755);
await writeFile(new URL("plugin/LICENSE", root), await readFile(new URL("LICENSE", root)));
await writeFile(new URL("plugin/THIRD_PARTY_NOTICES.md", root), await bundledNotices(result.metafile, root.pathname.replace(/\/$/u, "")));

const schema = spawnSync(process.execPath, [output.pathname, "schema"], {
  cwd: root,
  encoding: "utf8",
  maxBuffer: 8 * 1024 * 1024
});
if (schema.status !== 0) {
  process.stderr.write(schema.stderr);
  process.exit(schema.status ?? 1);
}
JSON.parse(schema.stdout);
await mkdir(new URL("plugin/schemas/", root), { recursive: true });
await writeFile(new URL("plugin/schemas/grokpair-tools.schema.json", root), schema.stdout);

for (const [path, value] of Object.entries(generatedFiles(packageJson))) {
  const target = new URL(path, root);
  await mkdir(dirname(target.pathname), { recursive: true });
  await writeFile(target, serialize(value));
}
