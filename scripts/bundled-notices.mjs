import { readFile, readdir } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/** Collect legal texts for packages that actually contribute bytes to the bundle. */
export async function bundledNotices(metafile, root) {
  const packages = new Map();
  // This production build emits esbuild's runtime helpers. They have no
  // package input in its metafile, so the compiler is an explicit contributor.
  const compilerDirectory = dirname(fileURLToPath(import.meta.resolve("esbuild/package.json")));
  const compiler = JSON.parse(await readFile(join(compilerDirectory, "package.json"), "utf8"));
  packages.set(`${compiler.name}@${compiler.version}`, { directory: compilerDirectory, pkg: compiler });
  for (const input of Object.keys(metafile.inputs)) {
    if (!Object.values(metafile.outputs).some(output => output.inputs?.[input]?.bytesInOutput > 0)) continue;
    let directory = dirname(resolve(root, input));
    while (directory !== dirname(directory)) {
      let pkg;
      try { pkg = JSON.parse(await readFile(join(directory, "package.json"), "utf8")); }
      catch (error) { if (error.code !== "ENOENT") throw error; }
      if (pkg?.name && pkg?.version) {
        if (directory !== root) packages.set(`${pkg.name}@${pkg.version}`, { directory, pkg });
        break;
      }
      directory = dirname(directory);
    }
    if (directory === dirname(directory)) throw new Error(`No package owner for bundled input ${input}`);
  }
  const sections = [];
  for (const [identity, { directory, pkg }] of [...packages.entries()].sort(([a], [b]) => a.localeCompare(b, "en"))) {
    const filenames = (await readdir(directory)).filter(name => /^(?:licen[cs]e|copying|notice)(?:$|[.-])/iu.test(name)).sort();
    if (!filenames.length) throw new Error(`No license text found for bundled dependency ${identity}`);
    const texts = await Promise.all(filenames.map(async name => `### ${name}\n\n${(await readFile(join(directory, name), "utf8")).trim()}`));
    sections.push(`## ${identity}\n\nDeclared license: ${pkg.license ?? "see license text"}\n\n${texts.join("\n\n")}`);
  }
  return `# Bundled third-party notices\n\nGenerated by scripts/bundled-notices.mjs from the production bundle's contributing packages, including esbuild's injected runtime helpers.\nGrokpair's own license is in LICENSE. Dependency license and notice texts follow verbatim.\n\n${sections.join("\n\n")}\n`;
}
